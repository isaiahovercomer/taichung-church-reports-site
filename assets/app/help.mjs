/** 產生說明頁內容（h 為 main.mjs 的元素工廠） */
export function helpView(h, { loggedIn = false } = {}) {
  return h(
    'section',
    { class: 'panel help', 'data-testid': 'help' },
    h('h1', { class: 'page-title', text: '使用說明' }),
    h('p', { class: 'hint', text: loggedIn ? '想看互動式的導覽，可以按上方的「使用教學」。' : '登入後可以按上方的「使用教學」看互動式導覽。' }),
    h('nav', { class: 'help-toc', 'aria-label': '目錄' }, SECTIONS.map((s) => h('button', { type: 'button', class: 'help-toc-link', 'data-target': s.id, text: s.title, onclick: () => {
      document.getElementById(`help-${s.id}`)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
    } }))),
    SECTIONS.map((s) => h('section', { class: 'help-section', id: `help-${s.id}`, 'data-section': s.id }, h('h2', { text: s.title }), h('ul', {}, s.items.map((t) => h('li', { text: t }))))),
    h('p', {}, h('a', { class: 'btn', href: '#/', text: loggedIn ? '回到我的行動' : '回到登入' })),
  );
}
